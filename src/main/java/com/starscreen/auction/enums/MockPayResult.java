package com.starscreen.auction.enums;

/**
 * 模拟支付通道的回调结果。
 *
 * <p>真实网关的通知通常只有"成功"，失败/取消要么通过"查询接口"拿，
 * 要么根本没有通知（用户直接关页面）。模拟实现把三种结果都显式建模，
 * 是为了让业务侧的每一条分支都能被主动触发、被测试覆盖——
 * 这正是"模拟支付"存在的意义：不是为了让流程跑通，而是为了让<b>异常分支</b>也能跑通。
 */
public enum MockPayResult {

    /** 支付成功。 */
    SUCCESS,

    /** 支付失败（余额不足、风控拒绝等）。 */
    FAIL,

    /** 用户主动取消，或超时未付关闭。 */
    CANCEL
}
